import { createRequire } from 'node:module';
import { resolve } from 'node:path';
import { mkdir, writeFile } from 'node:fs/promises';
const require = createRequire(resolve('frontend/package.json'));
const { chromium } = require('@playwright/test');
const AxeBuilder = require('@axe-core/playwright').default;
const browser = await chromium.launch();
const context = await browser.newContext();
const page = await context.newPage();
const evidence = { axe: [], errors: [] };
page.on('pageerror', e => evidence.errors.push(e.message));
await page.goto('http://127.0.0.1:8117/');
evidence.axe.push({ page: 'login', violations: (await new AxeBuilder({page}).analyze()).violations.map(v=>v.id) });
await page.getByLabel('Benutzername').fill('admin');
await page.getByLabel('Passwort', {exact:true}).fill('Test-password-for-browser!');
await page.getByRole('button', {name:'Anmelden',exact:true}).click();
await page.getByRole('heading', {name:'Überblick',exact:true}).waitFor();
for (const [path, title] of [['/', 'Überblick'],['/services','Dienste'],['/datasets','Testdaten'],['/criteria','Kriterien'],['/providers','LLM-Anbindung'],['/plans','Prüfprofile'],['/runs','Prüfläufe'],['/schedules','Zeitpläne'],['/users','Team']]) {
  await page.goto('http://127.0.0.1:8117'+path);
  await page.getByRole('heading', {name:title,exact:true}).waitFor();
  const scan = await new AxeBuilder({page}).analyze();
  evidence.axe.push({page:path,violations:scan.violations.map(v=>({id:v.id,impact:v.impact,count:v.nodes.length}))});
}
await page.goto('http://127.0.0.1:8117/');
await page.getByRole('heading', {name:'Überblick',exact:true}).waitFor();
await page.setViewportSize({width:375,height:667});
const menu = page.getByRole('button', {name:'Navigation öffnen',exact:true});
await menu.click();
const box = await menu.boundingBox();
const covered = await page.evaluate(({x,y})=>document.elementFromPoint(x,y)?.closest('aside')!==null,{x:box.x+box.width/2,y:box.y+box.height/2});
await page.keyboard.press('Escape');
evidence.mobile_menu = {toggle_covered_by_navigation:covered,still_open_after_escape:await page.locator('aside').evaluate(e=>e.classList.contains('open')),close_button_count:await page.locator('aside').getByRole('button',{name:/Schließen/}).count()};
await page.setViewportSize({width:1280,height:900});
await page.goto('http://127.0.0.1:8117/');
await page.getByRole('heading', {name:'Überblick',exact:true}).waitFor();
await page.route('**/api/demo', async route=>{const response=await route.fetch();await new Promise(resolve=>setTimeout(resolve,1000));await route.fulfill({response});});
await page.getByRole('button', {name:'Demo einrichten',exact:true}).click();
await page.getByRole('link', {name:'Zeitpläne',exact:true}).click();
await page.waitForURL('**/schedules');
await page.getByRole('button', {name:'Neu anlegen',exact:true}).click();
await page.waitForURL('**/plans');
evidence.pending_demo_navigation = {destination:new URL(page.url()).pathname};
await browser.close();
await mkdir('artifacts', {recursive:true});
await writeFile('artifacts/audit-ui.json',JSON.stringify(evidence,null,2));
console.log(JSON.stringify(evidence,null,2));
